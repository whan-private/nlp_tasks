GAME_RULES = """\
## 狼人杀游戏规则

### 基本设定
- 游戏分为两个阵营：狼人阵营（Werewolf）和好人阵营（Village）
- 狼人阵营获胜条件：所有反对者出局
- 好人阵营获胜条件：所有狼人出局

### 角色能力
- **狼人**：夜间与同伴共同选择一名玩家击杀
- **预言家**：夜间可选择一名玩家查验其阵营
- **女巫**：拥有一瓶解药和一瓶毒药。夜间知晓被狼人杀的玩家，可用解药救活；可用毒药毒杀任意玩家
- **村民**：无特殊能力，白天参与讨论和投票

### 游戏流程
1. **夜晚阶段**：狼人杀人 → 预言家验人 → 女巫救人/毒人
2. **白天阶段**：公布夜间死讯 → 玩家依次发言 → 投票放逐 → 被放逐者遗言
3. 昼夜交替直到一方获胜
"""

