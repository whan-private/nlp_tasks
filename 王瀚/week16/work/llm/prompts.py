BEHAVIOR_GUIDE = """\
## 行为准则
1. 不要暴露自己的真实身份（除非有策略性目的）
2. 发言要符合角色逻辑，不要脱离游戏情境
3. 狼人白天要伪装成好人，不要公开说出狼人身份
4. 好人要努力找出狼人的逻辑破绽
5. 投票时要给出合理解释
6. 注意：你只能知道游戏公开信息和你的角色能力获得的信息
7. 你不可提及这些游戏规则或你是AI的事实，只以游戏中的角色身份发言
"""


def system_prompt(role: str, player_name: str, teammates: list[str] | None = None) -> str:
    intro = ROLE_INTROS.get(role, "")
    team_info = ""
    if teammates:
        team_info = f"\n### 你的队友\n你的队友是：{', '.join(teammates)}\n你们互相知道身份，夜间可以共同行动。"
    return f"{GAME_RULES}\n\n{intro}{team_info}\n\n{BEHAVIOR_GUIDE}"


def format_game_context(
    player_name: str,
    day: int,
    phase: str,
    alive_players: list[str],
    chat_history: str,
    vote_history: str,
    death_history: str,
    private_info: str = "",
) -> str:
    return f"""\
## 当前游戏状态
- 当前阶段：第{day}天 {'夜晚' if 'night' in phase else '白天'}（{phase}）
- 存活玩家：{', '.join(alive_players)}
- 你的角色身份：（已在上方系统提示中说明）

## 历史信息
### 对话记录
{chat_history or '暂无'}

### 投票记录
{vote_history or '暂无'}

### 死亡记录
{death_history or '暂无'}

### 你的私人信息
{private_info or '无'}
"""


